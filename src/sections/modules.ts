export function buildModules(): HTMLElement {
  const cfg = C.modules as unknown as Record<string, any>;
  return buildShowcaseSection({
    sectionId: "modules",
    eyebrow: cfg?.eyebrow ?? "System Architecture",
    title: cfg?.title ?? "8 Operational Modules",
    subtitle:
      cfg?.sub ??
      "Every plan includes all eight working modules — attendance, projects, client vaults, time tracking, team management, business analysis, and workload.",
    items: modules,
    eventName: "modules:set",
    datasetAttr: "activeModule",
    layoutExtraClass: "modules-layout",
  });
}
